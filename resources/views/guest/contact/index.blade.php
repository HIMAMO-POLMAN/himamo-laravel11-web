    <script>
        const scriptURL =
            'https://script.google.com/macros/s/AKfycbwFXMLKZPnDbaLvm-siRDLfSwaBodlmty_F9XvVKv9BKQ-wH836iB6qaEl3MrN1v7nT/exec';
        const form = document.forms['submit-to-google-sheet'];
        const kirim = document.querySelector('.btn-kirim');
        const loading = document.querySelector('.btn-load');

        form.addEventListener('submit', e => {
            e.preventDefault();

            let formData = new FormData(form);
            loading.classList.toggle('d-none');
            kirim.classList.toggle('d-none');

            fetch(scriptURL, {
                    method: 'POST',
                    body: formData,
                    cache: "no-store"
                })
                .then(response => response.json())
                .then(data => {
                    console.log("Form berhasil dikirim:", data);
                    Swal.fire({
                        title: 'Berhasil!',
                        text: 'Pesan Anda berhasil dikirim.',
                        icon: 'success',
                        confirmButtonText: 'OK',
                        confirmButtonColor: '#028784'
                    });
                    form.reset();
                    loading.classList.toggle('d-none');
                    kirim.classList.toggle('d-none');
                })
                .catch(error => {
                    console.error('Kesalahan saat mengirim:', error);
                    Swal.fire({
                        title: 'Kesalahan!',
                        text: 'Terjadi kesalahan saat mengirim. Coba lagi nanti.',
                        icon: 'error',
                        confirmButtonText: 'Kembali',
                        confirmButtonColor: '#028784'
                    });
                    form.reset();
                    loading.classList.toggle('d-none');
                    kirim.classList.toggle('d-none');
                });
        });
    </script>
